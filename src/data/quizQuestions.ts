export function getRandomQuizQuestion(excludeId?: string): QuizQuestion {
  const filtered = excludeId
    ? TRICKY_QUIZ_QUESTIONS.filter(q => q.id !== excludeId)
    : TRICKY_QUIZ_QUESTIONS;
  const list = filtered.length > 0 ? filtered : TRICKY_QUIZ_QUESTIONS;
  const index = Math.floor(Math.random() * list.length);
  return list[index];
}
